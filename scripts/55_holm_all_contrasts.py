"""Holm-Bonferroni over every contrast of the credit map (docs/preregistration_round2.md, Section 4).

Reads the paired per-seed deltas that scripts/51_transfer_credit_tables.py
stores, runs a two-sided paired t-test of mean delta = 0 per contrast, and
adjusts across all contrasts in the JSON, including the 1,000 s ASSIST2012
rows. The result is printed beside the credit outcome; it is not a credit
rule. Does not retrain anything.

    python scripts/55_holm_all_contrasts.py
    python scripts/55_holm_all_contrasts.py --n-seeds 10
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from scipy import stats

REPO = Path(__file__).resolve().parents[1]
TABLES = REPO / "results" / "tables"
ALPHA = 0.05


def _holm(pvalues: list[float]) -> list[float]:
    order = sorted(range(len(pvalues)), key=lambda i: pvalues[i])
    adjusted = [0.0] * len(pvalues)
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, pvalues[i] * (len(pvalues) - rank)))
        adjusted[i] = running
    return adjusted


def _milli(value: float) -> str:
    return f"{1000 * value:+.2f}"


def _p(value: float) -> str:
    if value < 1e-4:
        mantissa, exponent = f"{value:.1e}".split("e")
        return f"${mantissa}\\times10^{{{int(exponent)}}}$"
    return f"${value:.4f}$"


def _split_by_corpus(rows: list[dict]) -> list[list[dict]]:
    """Two parts, cut at the corpus boundary closest to the middle."""
    cuts = [i for i in range(1, len(rows)) if rows[i]["corpus"] != rows[i - 1]["corpus"]]
    if not cuts:
        return [rows]
    cut = min(cuts, key=lambda i: abs(i - len(rows) / 2))
    return [rows[:cut], rows[cut:]]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-seeds", type=int, choices=(5, 10), default=5)
    args = parser.parse_args()
    suffix = "" if args.n_seeds == 5 else "_10seed"
    source = TABLES / f"credit_ladder_transfer{suffix}.json"
    rows = json.loads(source.read_text(encoding="utf-8"))["rows"]
    if not rows:
        raise SystemExit(f"{source.name} has no complete rows")

    tests = []
    for row in rows:
        result = stats.ttest_1samp(row["delta_val"], 0.0)
        tests.append(
            {
                "corpus": row["corpus"],
                "contrast": row["contrast"],
                "n_seeds": len(row["delta_val"]),
                "mean_delta_val": row["mean_delta_val"],
                "t": float(result.statistic),
                "p_two_sided": float(result.pvalue),
                "outcome_abs": row["outcome_abs"],
                "outcome_ci": row["outcome_ci"],
            }
        )
    for test, p_holm in zip(tests, _holm([t["p_two_sided"] for t in tests])):
        test["p_holm"] = p_holm
        test["reject_holm"] = p_holm < ALPHA

    out_json = TABLES / f"holm_all_contrasts{suffix}.json"
    out_json.write_text(
        json.dumps(
            {
                "source": source.name,
                "test": "two-sided one-sample t-test of paired deltas, H0: mean = 0",
                "family_size": len(tests),
                "alpha": ALPHA,
                "note": "Reported beside the credit outcome; not a credit rule.",
                "tests": tests,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    n = args.n_seeds
    label = "tab:holm-all" + ("" if n == 5 else "-10seed")
    short = {"Credited": "Credited", "Consistent-positive, not credited": "Cons.-pos.", "Unsupported": "Unsupp."}
    rules_differ = any(t["outcome_abs"] != t["outcome_ci"] for t in tests)
    caption = [
        f"Paired two-sided $t$-tests of mean difference $=0$ over {n}",
        f"seeds, Holm-adjusted across all {len(tests)} contrasts ($\\alpha=0.05$).",
        "Reported beside the credit outcome; Holm is not a credit rule. Mean is",
        "in units of $10^{-3}$ validation AUC."
        + " Credit: C credited, P consistent-positive (not credited), U unsupported"
        + ("; seed rule/interval rule where they differ." if rules_differ else "."),
    ]
    short = {"Credited": "C", "Consistent-positive, not credited": "P", "Unsupported": "U"}
    header = "Setting & Contrast & Mean & $p$ & $p_{\\mathrm{Holm}}$ & Credit \\\\"

    def credit(t: dict) -> str:
        if t["outcome_abs"] == t["outcome_ci"]:
            return short[t["outcome_abs"]]
        return f"{short[t['outcome_abs']]}/{short[t['outcome_ci']]}"

    lines = ["% Generated by scripts/55_holm_all_contrasts.py"]
    parts = _split_by_corpus(tests) if n != 5 else [tests]
    for k, part in enumerate(parts):
        if k == 0:
            cap = caption[:-1] + [caption[-1] + (f" Continued in Table~\\ref{{{label}-b}}." if len(parts) > 1 else "")]
            lab = label
        else:
            cap = [f"Holm-adjusted paired $t$-tests, continued from Table~\\ref{{{label}}}."]
            lab = f"{label}-b"
        cap[0] = "\\caption{" + cap[0]
        cap[-1] += "}"
        lines += [
            "\\begin{table}[tbp]" if len(parts) > 1 else "\\begin{table}[H]",
            *cap,
            f"\\label{{{lab}}}",
            "\\centering",
            "\\scriptsize",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\renewcommand{\\arraystretch}{0.84}",
            "\\begin{tabular}{@{}llrrrl@{}}",
            "\\toprule",
            header,
            "\\midrule",
        ]
        last = None
        for t in part:
            if last is not None and t["corpus"] != last:
                lines.append("\\addlinespace")
            corpus = t["corpus"] if t["corpus"] != last else ""
            last = t["corpus"]
            lines.append(
                f"{corpus} & {t['contrast']} & ${_milli(t['mean_delta_val'])}$ & {_p(t['p_two_sided'])} & "
                f"{_p(t['p_holm'])} & {credit(t)} \\\\"
            )
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    out_tex = REPO / "paper" / "tables" / f"table_holm_all_contrasts{suffix}.tex"
    out_tex.write_text("\n".join(lines), encoding="utf-8")

    for t in tests:
        print(
            f"{t['corpus']:28} {t['contrast']:40} mean={t['mean_delta_val']:+.6f} "
            f"p={t['p_two_sided']:.2e} holm={t['p_holm']:.2e} "
            f"{'reject' if t['reject_holm'] else 'keep  '} | {t['outcome_abs']}"
        )
    print(f"family={len(tests)} rejected={sum(t['reject_holm'] for t in tests)}")
    print(f"wrote {out_json}")
    print(f"wrote {out_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
