"""Threshold sensitivity on every row of the credit map (docs/preregistration_round2.md, Section 4).

For tau in {1.0, 1.5, 2.0, 2.5, 3.0} x 1e-3, recounts the seed rule (seeds
with delta >= tau) and the interval rule (mean - t * SD / sqrt(n) >= tau)
from the paired deltas stored by scripts/51_transfer_credit_tables.py.
tau = 2e-3 reproduces the credit map. Extends the XES3G5M-only recount of
scripts/45. Does not retrain anything.

    python scripts/56_threshold_all_corpora.py
    python scripts/56_threshold_all_corpora.py --n-seeds 10
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TABLES = REPO / "results" / "tables"
THRESHOLDS = (0.0010, 0.0015, 0.0020, 0.0025, 0.0030)
T_975_DF = {5: 2.7764451051977987, 10: 2.2621571627409915}
SHORT = {"Credited": "C", "Consistent-positive, not credited": "P", "Unsupported": "U"}


def _outcome(credited: bool, deltas: list[float]) -> str:
    if credited:
        return "Credited"
    if all(d > 0 for d in deltas):
        return "Consistent-positive, not credited"
    return "Unsupported"


def _split_by_corpus(rows: list[dict]) -> list[list[dict]]:
    """Two parts, cut at the corpus boundary closest to the middle."""
    cuts = [i for i in range(1, len(rows)) if rows[i]["corpus"] != rows[i - 1]["corpus"]]
    if not cuts:
        return [rows]
    cut = min(cuts, key=lambda i: abs(i - len(rows) / 2))
    return [rows[:cut], rows[cut:]]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-seeds", type=int, choices=(5, 10), default=5)
    args = parser.parse_args()
    n = args.n_seeds
    suffix = "" if n == 5 else "_10seed"
    source = TABLES / f"credit_ladder_transfer{suffix}.json"
    rows = json.loads(source.read_text(encoding="utf-8"))["rows"]
    if not rows:
        raise SystemExit(f"{source.name} has no complete rows")
    t975 = T_975_DF[n]

    out_rows = []
    for row in rows:
        deltas = row["delta_val"]
        lcb = row["mean_delta_val"] - t975 * row["sd_delta_val"] / math.sqrt(len(deltas))
        by_tau = {}
        for tau in THRESHOLDS:
            by_tau[f"{tau:.4f}"] = {
                "pass_seed": sum(d >= tau for d in deltas),
                "outcome_seed": _outcome(all(d >= tau for d in deltas), deltas),
                "outcome_interval": _outcome(lcb >= tau, deltas),
            }
        at_ref = by_tau["0.0020"]
        if at_ref["outcome_seed"] != row["outcome_abs"] or at_ref["outcome_interval"] != row["outcome_ci"]:
            raise SystemExit(f"tau=0.002 does not reproduce the map for {row['corpus']}: {row['contrast']}")
        stable = len({v["outcome_seed"] for v in by_tau.values()} | {v["outcome_interval"] for v in by_tau.values()}) == 1
        out_rows.append(
            {
                "corpus": row["corpus"],
                "contrast": row["contrast"],
                "mean_delta_val": row["mean_delta_val"],
                "min_delta_val": row["min_delta_val"],
                "lcb95_delta_val": lcb,
                "by_tau": by_tau,
                "stable_over_grid": stable,
            }
        )

    out_json = TABLES / f"threshold_sensitivity_all_corpora{suffix}.json"
    out_json.write_text(
        json.dumps(
            {
                "source": source.name,
                "thresholds": list(THRESHOLDS),
                "t_975": t975,
                "n_seeds": n,
                "rows": out_rows,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    label = "tab:threshold-all" + ("" if n == 5 else "-10seed")
    head = " & ".join(f"${1000 * tau:.1f}$" for tau in THRESHOLDS)
    parts = _split_by_corpus(out_rows) if n != 5 else [out_rows]
    lines = ["% Generated by scripts/56_threshold_all_corpora.py"]
    for k, part in enumerate(parts):
        if k == 0:
            cap = [
                f"\\caption{{Credit outcome as the threshold $\\tau$ (units of $10^{{-3}}$",
                f"validation AUC) varies, every row of the map, {n} paired seeds. Each",
                "cell is the seed-rule outcome and pass count; a second letter is the",
                "interval-rule outcome where it differs. C: credited; P:",
                "consistent-positive (not credited); U: unsupported. $\\tau=2.0$ is the",
                "credit map." + (f" Continued in Table~\\ref{{{label}-b}}.}}" if len(parts) > 1 else "}"),
                f"\\label{{{label}}}",
            ]
        else:
            cap = [
                f"\\caption{{Threshold recount, continued from Table~\\ref{{{label}}}.}}",
                f"\\label{{{label}-b}}",
            ]
        lines += [
            "\\begin{table}[tbp]" if len(parts) > 1 else "\\begin{table}[H]",
            *cap,
            "\\centering",
            "\\scriptsize",
            "\\setlength{\\tabcolsep}{1.5pt}",
            "\\renewcommand{\\arraystretch}{0.84}",
            f"\\begin{{tabular}}{{@{{}}ll{'c' * len(THRESHOLDS)}@{{}}}}",
            "\\toprule",
            f"Setting & Contrast & {head} \\\\",
            "\\midrule",
        ]
        last = None
        for r in part:
            if last is not None and r["corpus"] != last:
                lines.append("\\addlinespace")
            corpus = r["corpus"] if r["corpus"] != last else ""
            last = r["corpus"]
            cells = []
            for tau in THRESHOLDS:
                v = r["by_tau"][f"{tau:.4f}"]
                cell = SHORT[v["outcome_seed"]]
                if v["outcome_interval"] != v["outcome_seed"]:
                    cell += "/" + SHORT[v["outcome_interval"]]
                cells.append(f"{cell}\\,{v['pass_seed']}")
            lines.append(f"{corpus} & {r['contrast']} & " + " & ".join(cells) + " \\\\")
        lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    out_tex = REPO / "paper" / "tables" / f"table_threshold_all_corpora{suffix}.tex"
    out_tex.write_text("\n".join(lines), encoding="utf-8")

    for r in out_rows:
        cells = " ".join(
            SHORT[r["by_tau"][f"{tau:.4f}"]["outcome_seed"]]
            + SHORT[r["by_tau"][f"{tau:.4f}"]["outcome_interval"]]
            + str(r["by_tau"][f"{tau:.4f}"]["pass_seed"])
            for tau in THRESHOLDS
        )
        print(f"{r['corpus']:28} {r['contrast']:40} {cells} {'stable' if r['stable_over_grid'] else 'CHANGES'}")
    print(f"rows={len(out_rows)} stable={sum(r['stable_over_grid'] for r in out_rows)}")
    print(f"wrote {out_json}")
    print(f"wrote {out_tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
