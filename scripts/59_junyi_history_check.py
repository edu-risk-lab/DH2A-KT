"""Junyi history-only gap check (docs/preregistration_junyi_onset.md).

Junyi timestamps are completion times, so the query-side gap of row t+1
includes the time spent on item t+1. The ``junyi-hist`` group of
scripts/50_credit_ladder_plan.py feeds the gap to the recurrent side only.
This script pairs it by seed with the existing ``junyi-partial`` no-time
arm (package) and with its own T-zero arm (aligned gap), and applies both
credit rules on validation AUC, with test-only AUC beside them.

Writes results/tables/junyi_history_check.json and
paper/tables/table_junyi_history.tex. Does not retrain anything.

    python scripts/59_junyi_history_check.py
"""

from __future__ import annotations

import csv
import json
import math
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TABLES = REPO / "results" / "tables"
SEEDS = (0, 17, 42, 1234, 2024, 7, 99, 314, 2718, 3407)
TAU = 0.002
T_975 = 2.2621571627409915
OUT_JSON = TABLES / "junyi_history_check.json"
OUT_TEX = REPO / "paper" / "tables" / "table_junyi_history.tex"

CONTRASTS = (
    ("History-only package", "Package", "junyi-hist_time-history", "junyi-partial_no-time"),
    ("History-only gap vs.\\ T-zero", "Architecture", "junyi-hist_time-history", "junyi-hist_t-zero-history"),
    ("Query-and-history package", "Package", "junyi-partial_time-package", "junyi-partial_no-time"),
    ("Query-and-history gap vs.\\ T-zero", "Architecture", "junyi-partial_time-package", "junyi-partial_t-zero"),
)
SHORT = {"Credited": "Credited", "Consistent-positive, not credited": "Cons.-pos.", "Unsupported": "Unsupp."}


def _path(arm: str, seed: int) -> Path:
    return TABLES / f"dh2_kt_ladder_{arm}_s{seed}_vs_p0.csv"


def _read(arm: str) -> dict[int, dict[str, float]]:
    out = {}
    for seed in SEEDS:
        with _path(arm, seed).open(encoding="utf-8") as fh:
            row = next(csv.DictReader(fh))
        out[seed] = {"val": float(row["val_auc"]), "test": float(row["dh2_kt_auc"])}
    return out


def _outcome(credited: bool, deltas: list[float]) -> str:
    if credited:
        return "Credited"
    if all(d > 0 for d in deltas):
        return "Consistent-positive, not credited"
    return "Unsupported"


def _score(deltas: list[float]) -> dict:
    mean = statistics.mean(deltas)
    lcb = mean - T_975 * statistics.stdev(deltas) / math.sqrt(len(deltas))
    return {
        "deltas": deltas,
        "mean": mean,
        "lcb95": lcb,
        "pass_abs": sum(d >= TAU for d in deltas),
        "outcome_abs": _outcome(all(d >= TAU for d in deltas), deltas),
        "outcome_ci": _outcome(lcb >= TAU, deltas),
    }


def _cell(s: dict) -> str:
    if s["outcome_abs"] == s["outcome_ci"]:
        out = SHORT[s["outcome_ci"]]
    else:
        out = f"{SHORT[s['outcome_abs']]}/{SHORT[s['outcome_ci']]}"
    return f"${s['mean'] * 1e3:+.2f}$ [${s['lcb95'] * 1e3:+.2f}$] & {out} ${s['pass_abs']}/{len(SEEDS)}$"


def main() -> int:
    missing = sorted(
        {f"{arm} s{seed}" for _, _, on, ctrl in CONTRASTS for arm in (on, ctrl)
         for seed in SEEDS if not _path(arm, seed).exists()}
    )
    if missing:
        for m in missing:
            print(f"PENDING {m}")
        return 1
    rows = []
    for label, rung, on_arm, ctrl_arm in CONTRASTS:
        on, ctrl = _read(on_arm), _read(ctrl_arm)
        rows.append({
            "contrast": label,
            "rung": rung,
            "on": on_arm,
            "control": ctrl_arm,
            "val": _score([on[s]["val"] - ctrl[s]["val"] for s in SEEDS]),
            "test": _score([on[s]["test"] - ctrl[s]["test"] for s in SEEDS]),
        })
    OUT_JSON.write_text(json.dumps({"seeds": SEEDS, "tau": TAU, "rows": rows}, indent=2), encoding="utf-8")
    lines = [
        "% Generated by scripts/59_junyi_history_check.py",
        "\\begin{table}[tbp]",
        "\\caption{Junyi history-only check (first $50{,}000$ learners, fold~0,",
        "corpus configuration, ten paired seeds). Junyi timestamps are completion",
        "times, so the query-side gap includes the scored item's own duration;",
        "the history-only arms feed the gap to the recurrent input only. Means",
        "and lower 95\\% bounds in $10^{-3}$ AUC; outcomes are seed rule/interval",
        "rule where they differ, with the number of seeds at the threshold. The",
        "last two rows repeat Table~\\ref{tab:credit-transfer-10seed-b}.}",
        "\\label{tab:junyi-history}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrlrl@{}}",
        "\\toprule",
        "Contrast & Validation [lower] & Outcome & Test-only [lower] & Outcome \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(f"{r['contrast']} & {_cell(r['val'])} & {_cell(r['test'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    OUT_TEX.write_text("\n".join(lines), encoding="utf-8")
    for r in rows:
        print(f"{r['contrast']:40} val {r['val']['mean']:+.5f} [{r['val']['lcb95']:+.5f}] "
              f"{r['val']['outcome_abs']} / {r['val']['outcome_ci']} | test {r['test']['mean']:+.5f} "
              f"[{r['test']['lcb95']:+.5f}] {r['test']['outcome_ci']}")
    print(f"wrote {OUT_JSON}\nwrote {OUT_TEX}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
